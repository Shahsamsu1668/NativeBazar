export const getDistrictNames = (): string[] => BANGLADESH_LOCATIONS.map((l) => l.district);

export const getDistrictByName = (name: string): DistrictLocation | undefined => {
  const q = (name || '').trim().toLowerCase();
  return BANGLADESH_LOCATIONS.find(
    (l) => l.district.toLowerCase() === q || l.districtBn.toLowerCase() === q
  );
};

export const getUpazilasByDistrict = (districtName: string): string[] => {
  const match = getDistrictByName(districtName);
  return match ? match.upazilas : [];
};

